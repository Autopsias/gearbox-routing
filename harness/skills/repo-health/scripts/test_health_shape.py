def test_what_actually_disqualifies_a_requirements_file(tmp_path):
    """The catalog's content-sniff sentence, run line by line.

    A `#` heading is NOT in this list on purpose: pip reads it as a comment, so
    it is stripped before the sniff and disqualifies nothing. The catalog used
    to claim it did.
    """
    import shape
    pip = "pytest==9.1.1\n"
    cases = {
        "The system must render a monthly summary.": False,   # a sentence
        "- login": False,                                     # a markdown bullet
        "# Requirements Document": True,                      # a comment to pip
        "    # via requests": True,                           # pip-compile's own
    }
    for i, (line, still_counts) in enumerate(cases.items()):
        repo = tmp_path / f"sniff{i}"
        repo.mkdir()
        (repo / "requirements.txt").write_text(pip + line + "\n")
        assert shape.is_requirements(repo, "requirements.txt") is still_counts, \
            f"{line!r}: expected the file to {'still count' if still_counts else 'be rejected'}"


