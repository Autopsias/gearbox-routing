def test_the_requirement_line_parser_separates_specs_from_prose():
    """The regex alone matches functional_requirements.txt; this is what does not."""
    import shape
    for ln in ("pytest==9.1.1", "PyYAML >= 6.0", "black[jupyter]==24.1",
               "requests @ https://example.invalid/r.whl",
               "numpy; python_version < '3.12'", "django",
               "certifi==2024.2.2 \\",                      # pip-compile continuation
               "git+https://github.com/foo/bar@main#egg=bar",
               "-e git+https://github.com/foo/bar@main#egg=bar"):
        assert shape._requirement_spec(ln), f"missed a real requirement: {ln!r}"
    for ln in ("# a comment", "", "   ", "Functional requirements",
               "The system must render a monthly summary for every account.",
               "Access is restricted to users with the finance role.",
               "- Access is restricted to users with the finance role.",
               "- login", "    # via requests"):
        assert not shape._requirement_spec(ln), f"prose parsed as a requirement: {ln!r}"


def test_pip_options_are_pip_syntax_but_never_dependencies():
    """The two questions one predicate used to answer with one answer.

    A `--hash=` line proves the file is a requirements file AND is not a
    dependency; conflating those reported every hash-pinned file as unpinned.
    """
    import shape
    for ln in ("-r base.txt", "-c constraints.txt", "-e .",
               "--index-url https://example.invalid/simple",
               "--hash=sha256:0569859f95fc761b18b45ef421b1290a0f65f147e92a1e5e",
               "--require-hashes"):
        assert shape._pip_option(ln), f"missed pip syntax: {ln!r}"
        assert not shape._requirement_spec(ln), f"counted as a dependency: {ln!r}"
    for ln in ("- Access is restricted to users with the finance role.",
               "- login", "Requirements", "pytest==9.1.1"):
        assert not shape._pip_option(ln), f"prose/spec read as pip syntax: {ln!r}"


