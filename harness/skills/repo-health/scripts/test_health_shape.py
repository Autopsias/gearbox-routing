def test_a_hash_pinned_file_is_not_reported_as_unpinned(tmp_path):
    """--hash= and -r are pip syntax, not dependencies.

    One predicate was answering two questions ("is this file a manifest?" and
    "is this line an unpinned dependency?") and gave the option lines the same
    answer to both, so the most tightly pinned file a repo can have — pip-compile
    output with hashes — reported as unpinned.
    """
    import shape as shape_mod
    repo = make_repo(tmp_path, "hashpin", {
        "requirements.txt": HASH_PINNED,
        "requirements-dev.txt": "-r requirements.txt\npytest==9.1.1\n",
        "app.py": "x = 1\n"})
    files = health.tracked_files(repo)
    detected = health.detect_shape(repo, files)["manifests"]
    assert sorted(detected) == ["requirements-dev.txt", "requirements.txt"]
    assert shape_mod.unpinned_requirements(repo, detected) == ([], [])
    health.collect(repo)
    c = next(c for c in card(repo)["checks"] if c["id"] == "ai.lockfiles")
    assert "unpinned" not in c["detail"], c["detail"]


def test_vcs_requirements_are_visible_and_a_branch_ref_is_unpinned(tmp_path):
    """A branch reference is the least pinned thing a requirements file can hold."""
    import shape as shape_mod
    repo = make_repo(tmp_path, "vcs", {
        "requirements.txt": VCS_REQS, "app.py": "x = 1\n"})
    files = health.tracked_files(repo)
    assert health.detect_shape(repo, files)["manifests"] == ["requirements.txt"]
    assert shape_mod.unpinned_requirements(repo, ["requirements.txt"]) \
        == (["requirements.txt"], [])
    # the commit-pinned sibling on its own is pinned
    (repo / "requirements.txt").write_text(VCS_REQS.splitlines()[1] + "\n")
    assert shape_mod.unpinned_requirements(repo, ["requirements.txt"]) == ([], [])


# ---------- an unopenable pyproject.toml/setup.cfg reaches `unread` too ----------

def test_an_unopenable_pyproject_toml_is_named_not_skipped(tmp_path):
    """unpinned_requirements() used to filter on `is_requirements()` FIRST — a
    basename test that pyproject.toml/setup.cfg never match — so an unopenable
    one of those never even reached `read_or_unread` and never landed in
    `unread`. `is_manifest` already counts it as a manifest when it will not
    open, so it stayed in `shape["manifests"]`, and `ai.lockfiles` read "no
    unpinned requirements found" over a file nobody had opened.
    """
    import shape as shape_mod
    repo = make_repo(tmp_path, "unreadpp", {
        "pyproject.toml": '[project]\ndependencies = ["requests>=2.0"]\n',
        "uv.lock": "# lock\n", "a.py": "x = 1\n"})
    (repo / "pyproject.toml").unlink()
    unpinned, unread = shape_mod.unpinned_requirements(
        repo, ["pyproject.toml"], health.tracked_files(repo))
    assert unpinned == [], "an unread file has no measured spec to be unpinned"
    assert unread == ["pyproject.toml"], \
        "an unopenable claimed manifest never reached `unread`"


