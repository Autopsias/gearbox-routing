def git(repo, *args):
    subprocess.run(["git", "-C", str(repo), "-c", "user.email=t@t",
                    "-c", "user.name=t", *args], check=True, capture_output=True)


def make_repo(tmp_path, name, files):
    repo = tmp_path / name
    repo.mkdir(parents=True)
    subprocess.run(["git", "init", "-q"], cwd=repo, check=True)
    for rel, body in files.items():
        p = repo / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(body)
    git(repo, "add", "-A")
    git(repo, "commit", "-qm", "init")
    return repo


def card(repo):
    return json.loads((repo / ".claude" / "health" / "scorecard.json").read_text())


def statuses(repo):
    return {c["id"]: c["status"] for c in card(repo)["checks"]}


def details(repo):
    return {c["id"]: c["detail"] for c in card(repo)["checks"]}


